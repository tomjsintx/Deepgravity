package com.example.llm

import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import okhttp3.MediaType.Companion.toMediaType
import okhttp3.OkHttpClient
import okhttp3.Request
import okhttp3.RequestBody.Companion.toRequestBody
import org.json.JSONArray
import org.json.JSONObject
import java.io.IOException
import java.util.concurrent.TimeUnit

class LlmClient(
    private val okHttpClient: OkHttpClient = OkHttpClient.Builder()
        .connectTimeout(30, TimeUnit.SECONDS)
        .readTimeout(60, TimeUnit.SECONDS)
        .writeTimeout(30, TimeUnit.SECONDS)
        .build()
) {

    private val jsonMediaType = "application/json; charset=utf-8".toMediaType()

    suspend fun executeCompletion(
        providerConfig: ProviderConfig,
        apiKey: String?,
        request: LlmCompletionRequest
    ): Result<LlmCompletionResponse> = withContext(Dispatchers.IO) {
        val startTime = System.currentTimeMillis()

        if (providerConfig.providerType.requiresApiKey && (apiKey.isNullOrBlank())) {
            return@withContext Result.failure(
                IllegalArgumentException("API key for ${providerConfig.providerType.displayName} is missing. Please configure it in Providers.")
            )
        }

        try {
            val response = when (providerConfig.providerType) {
                ProviderType.GEMINI -> executeGemini(providerConfig, apiKey ?: "", request)
                ProviderType.CLAUDE -> executeClaude(providerConfig, apiKey ?: "", request)
                ProviderType.LOCAL_OLLAMA -> executeOllama(providerConfig, request)
                else -> executeOpenAiCompatible(providerConfig, apiKey ?: "", request)
            }
            val latency = System.currentTimeMillis() - startTime
            Result.success(response.copy(latencyMs = latency))
        } catch (e: Exception) {
            Result.failure(e)
        }
    }

    suspend fun pingProvider(providerConfig: ProviderConfig, apiKey: String?): Long? = withContext(Dispatchers.IO) {
        val start = System.currentTimeMillis()
        try {
            val requestBuilder = Request.Builder()
                .url(providerConfig.effectiveBaseUrl)
                .head()

            if (!apiKey.isNullOrBlank()) {
                requestBuilder.addHeader(
                    providerConfig.providerType.headerAuthKey,
                    "${providerConfig.providerType.authPrefix}$apiKey"
                )
            }

            val call = okHttpClient.newCall(requestBuilder.build())
            val response = call.execute()
            response.close()
            System.currentTimeMillis() - start
        } catch (e: Exception) {
            // Some endpoints fail on HEAD, fallback to quick check
            null
        }
    }

    private fun executeGemini(
        provider: ProviderConfig,
        apiKey: String,
        req: LlmCompletionRequest
    ): LlmCompletionResponse {
        val url = "${provider.effectiveBaseUrl}/models/${req.modelId}:generateContent?key=$apiKey"

        val rootJson = JSONObject()
        val contentsArray = JSONArray()

        req.messages.forEach { msg ->
            val partObj = JSONObject().put("text", msg.content)
            val partsArray = JSONArray().put(partObj)
            val role = if (msg.role == "assistant") "model" else "user"
            contentsArray.put(JSONObject().put("role", role).put("parts", partsArray))
        }
        rootJson.put("contents", contentsArray)

        if (!req.systemPrompt.isNullOrBlank()) {
            val sysPart = JSONObject().put("text", req.systemPrompt)
            rootJson.put("systemInstruction", JSONObject().put("parts", JSONArray().put(sysPart)))
        }

        // Thinking Config for Gemini 3.1 Pro Preview
        if (req.thinkingLevelHigh && req.modelId.contains("pro")) {
            val genConfig = JSONObject().put("thinkingConfig", JSONObject().put("thinkingLevel", "HIGH"))
            rootJson.put("generationConfig", genConfig)
        }

        val requestBody = rootJson.toString().toRequestBody(jsonMediaType)
        val httpRequest = Request.Builder()
            .url(url)
            .post(requestBody)
            .build()

        okHttpClient.newCall(httpRequest).execute().use { response ->
            if (!response.isSuccessful) {
                val errorBody = response.body?.string() ?: ""
                throw IOException("Gemini API Error ${response.code}: $errorBody")
            }

            val respBody = response.body?.string() ?: throw IOException("Empty response from Gemini")
            val respJson = JSONObject(respBody)

            val candidates = respJson.optJSONArray("candidates")
            if (candidates == null || candidates.length() == 0) {
                return LlmCompletionResponse(text = "No content generated by Gemini.")
            }

            val firstCandidate = candidates.getJSONObject(0)
            val contentObj = firstCandidate.optJSONObject("content")
            val parts = contentObj?.optJSONArray("parts")

            var generatedText = ""
            var thinkingText: String? = null

            if (parts != null) {
                for (i in 0 until parts.length()) {
                    val p = parts.getJSONObject(i)
                    if (p.has("thought")) {
                        thinkingText = (thinkingText ?: "") + p.optString("thought")
                    }
                    if (p.has("text")) {
                        generatedText += p.optString("text")
                    }
                }
            }

            return LlmCompletionResponse(
                text = generatedText.ifBlank { "Executed successfully." },
                thinkingTrace = thinkingText,
                finishReason = firstCandidate.optString("finishReason", "STOP")
            )
        }
    }

    private fun executeOpenAiCompatible(
        provider: ProviderConfig,
        apiKey: String,
        req: LlmCompletionRequest
    ): LlmCompletionResponse {
        val url = if (provider.effectiveBaseUrl.endsWith("/")) {
            "${provider.effectiveBaseUrl}chat/completions"
        } else {
            "${provider.effectiveBaseUrl}/chat/completions"
        }

        val rootJson = JSONObject()
        rootJson.put("model", req.modelId)
        rootJson.put("temperature", req.temperature)

        val messagesArray = JSONArray()
        if (!req.systemPrompt.isNullOrBlank()) {
            messagesArray.put(JSONObject().put("role", "system").put("content", req.systemPrompt))
        }
        req.messages.forEach { msg ->
            messagesArray.put(JSONObject().put("role", msg.role).put("content", msg.content))
        }
        rootJson.put("messages", messagesArray)

        val requestBody = rootJson.toString().toRequestBody(jsonMediaType)
        val httpRequest = Request.Builder()
            .url(url)
            .addHeader(provider.providerType.headerAuthKey, "${provider.providerType.authPrefix}$apiKey")
            .post(requestBody)
            .build()

        okHttpClient.newCall(httpRequest).execute().use { response ->
            if (!response.isSuccessful) {
                val errorBody = response.body?.string() ?: ""
                throw IOException("${provider.providerType.displayName} Error ${response.code}: $errorBody")
            }

            val respBody = response.body?.string() ?: throw IOException("Empty response")
            val respJson = JSONObject(respBody)

            val choices = respJson.optJSONArray("choices")
            if (choices == null || choices.length() == 0) {
                return LlmCompletionResponse(text = "No choice returned.")
            }

            val firstChoice = choices.getJSONObject(0)
            val msgObj = firstChoice.optJSONObject("message")
            val content = msgObj?.optString("content") ?: ""
            val reasoning = msgObj?.optString("reasoning_content", null)

            val usage = respJson.optJSONObject("usage")
            val pTokens = usage?.optInt("prompt_tokens")
            val cTokens = usage?.optInt("completion_tokens")

            return LlmCompletionResponse(
                text = content,
                thinkingTrace = reasoning,
                promptTokens = pTokens,
                completionTokens = cTokens,
                finishReason = firstChoice.optString("finish_reason")
            )
        }
    }

    private fun executeClaude(
        provider: ProviderConfig,
        apiKey: String,
        req: LlmCompletionRequest
    ): LlmCompletionResponse {
        val url = if (provider.effectiveBaseUrl.endsWith("/")) "${provider.effectiveBaseUrl}messages" else "${provider.effectiveBaseUrl}/messages"

        val rootJson = JSONObject()
        rootJson.put("model", req.modelId)
        rootJson.put("max_tokens", 4096)

        if (!req.systemPrompt.isNullOrBlank()) {
            rootJson.put("system", req.systemPrompt)
        }

        val messagesArray = JSONArray()
        req.messages.forEach { msg ->
            messagesArray.put(JSONObject().put("role", msg.role).put("content", msg.content))
        }
        rootJson.put("messages", messagesArray)

        val requestBody = rootJson.toString().toRequestBody(jsonMediaType)
        val httpRequest = Request.Builder()
            .url(url)
            .addHeader("x-api-key", apiKey)
            .addHeader("anthropic-version", "2023-06-01")
            .post(requestBody)
            .build()

        okHttpClient.newCall(httpRequest).execute().use { response ->
            if (!response.isSuccessful) {
                val errorBody = response.body?.string() ?: ""
                throw IOException("Claude Error ${response.code}: $errorBody")
            }

            val respBody = response.body?.string() ?: throw IOException("Empty response")
            val respJson = JSONObject(respBody)

            val contents = respJson.optJSONArray("content")
            var textResult = ""
            var thinkingResult: String? = null

            if (contents != null) {
                for (i in 0 until contents.length()) {
                    val item = contents.getJSONObject(i)
                    if (item.optString("type") == "text") {
                        textResult += item.optString("text")
                    } else if (item.optString("type") == "thinking") {
                        thinkingResult = item.optString("thinking")
                    }
                }
            }

            return LlmCompletionResponse(
                text = textResult,
                thinkingTrace = thinkingResult,
                finishReason = respJson.optString("stop_reason")
            )
        }
    }

    private fun executeOllama(
        provider: ProviderConfig,
        req: LlmCompletionRequest
    ): LlmCompletionResponse {
        val url = "${provider.effectiveBaseUrl}/api/chat"

        val rootJson = JSONObject()
        rootJson.put("model", req.modelId)
        rootJson.put("stream", false)

        val messagesArray = JSONArray()
        if (!req.systemPrompt.isNullOrBlank()) {
            messagesArray.put(JSONObject().put("role", "system").put("content", req.systemPrompt))
        }
        req.messages.forEach { msg ->
            messagesArray.put(JSONObject().put("role", msg.role).put("content", msg.content))
        }
        rootJson.put("messages", messagesArray)

        val requestBody = rootJson.toString().toRequestBody(jsonMediaType)
        val httpRequest = Request.Builder()
            .url(url)
            .post(requestBody)
            .build()

        okHttpClient.newCall(httpRequest).execute().use { response ->
            if (!response.isSuccessful) {
                val errorBody = response.body?.string() ?: ""
                throw IOException("Ollama Error ${response.code}: $errorBody")
            }

            val respBody = response.body?.string() ?: throw IOException("Empty response")
            val respJson = JSONObject(respBody)
            val msgObj = respJson.optJSONObject("message")
            val content = msgObj?.optString("content") ?: ""

            return LlmCompletionResponse(
                text = content,
                finishReason = if (respJson.optBoolean("done")) "STOP" else "RUNNING"
            )
        }
    }
}
